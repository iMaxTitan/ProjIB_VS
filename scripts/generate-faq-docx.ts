/* ── helpers ── */

function title(text: string): Paragraph {
  return new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun({ text, bold: true, size: 36 })] });
}

function subtitle(text: string): Paragraph {
  return new Paragraph({
    spacing: { before: 80 },
    children: [new TextRun({ text, italics: true, size: 24, color: '666666' })],
  });
}

function h1(text: string): Paragraph {
  return new Paragraph({ heading: HeadingLevel.HEADING_1, spacing: { before: 400 }, children: [new TextRun(text)] });
}

function h2(text: string): Paragraph {
  return new Paragraph({ heading: HeadingLevel.HEADING_2, spacing: { before: 240 }, children: [new TextRun(text)] });
}

function p(text: string): Paragraph {
  return new Paragraph({ spacing: { after: 120 }, children: [new TextRun(text)] });
}

function bold(text: string): Paragraph {
  return new Paragraph({ spacing: { after: 80 }, children: [new TextRun({ text, bold: true })] });
}

function bullet(text: string): Paragraph {
  return new Paragraph({
    bullet: { level: 0 },
    spacing: { after: 40 },
    children: [new TextRun(text)],
  });
}

function numberedItem(num: number, text: string): Paragraph {
  return new Paragraph({
    spacing: { after: 40 },
    children: [new TextRun({ text: `${num}. ${text}` })],
  });
}

function ref(text: string): Paragraph {
  return new Paragraph({
    spacing: { before: 120, after: 200 },
    children: [new TextRun({ text, italics: true, size: 20 })],
  });
}

function hr(): Paragraph {
  return new Paragraph({
    spacing: { before: 200, after: 200 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 1, color: '999999' } },
    children: [],
  });
}

