// ─── Типографические примитивы ───────────────────────────────────────────────

function H2({ id, children }: { id: string; children: React.ReactNode }) {
  return (
    <h2
      id={id}
      className="text-base font-semibold text-indigo-700 mt-6 mb-2 flex items-center gap-2"
    >
      {children}
    </h2>
  );
}

function H3({ children }: { children: React.ReactNode }) {
  return (
    <h3 className="text-sm font-semibold text-slate-700 mt-4 mb-1.5">
      {children}
    </h3>
  );
}

function P({ children }: { children: React.ReactNode }) {
  return <p className="text-sm text-slate-600 leading-relaxed mb-2">{children}</p>;
}

function UL({ children }: { children: React.ReactNode }) {
  return <ul className="text-sm text-slate-600 space-y-1 mb-3 pl-4 list-disc">{children}</ul>;
}

function LI({ children }: { children: React.ReactNode }) {
  return <li className="leading-relaxed">{children}</li>;
}

function Bold({ children }: { children: React.ReactNode }) {
  return <span className="font-medium text-slate-800">{children}</span>;
}

function Code({ children }: { children: React.ReactNode }) {
  return (
    <code className="px-1 py-0.5 bg-indigo-50 text-indigo-700 rounded text-xs font-mono">
      {children}
    </code>
  );
}

function Note({ children }: { children: React.ReactNode }) {
  return (
    <div className="mt-2 mb-3 flex gap-2 rounded-lg bg-indigo-50 border border-indigo-100 px-3 py-2">
      <span className="text-indigo-400 flex-shrink-0">ℹ</span>
      <p className="text-xs text-indigo-700 leading-relaxed">{children}</p>
    </div>
  );
}

function Divider() {
  return <hr className="border-slate-100 my-4" />;
}

interface TableProps {
  headers: string[];
  rows: (string | React.ReactNode)[][];
}

function Table({ headers, rows }: TableProps) {
  return (
    <div className="overflow-x-auto mb-3 rounded-lg border border-slate-200">
      <table className="w-full text-xs">
        <thead>
          <tr className="bg-slate-50 border-b border-slate-200">
            {headers.map((h) => (
              <th key={h} className="px-3 py-2 text-left font-semibold text-slate-600 whitespace-nowrap">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((row, i) => (
            <tr key={i} className={cn('border-b border-slate-100 last:border-0', i % 2 === 1 && 'bg-slate-50/50')}>
              {row.map((cell, j) => (
                <td key={j} className="px-3 py-2 text-slate-600 leading-relaxed">
                  {cell}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

